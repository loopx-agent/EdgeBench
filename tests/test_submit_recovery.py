@contextmanager
def drop_one_reply(judge, path):
    class Gateway(BaseHTTPRequestHandler):
        def forward(self):
            size = int(self.headers.get("Content-Length", "0"))
            response = judge.http.request(self.command, judge.url + self.path,
                data=self.rfile.read(size) if size else None,
                headers={"Content-Type": self.headers.get("Content-Type", "")}, timeout=5)
            matches = self.path.endswith(path) or (
                path == "result" and "/result/" in self.path
            )
            if matches and not self.server.dropped:
                self.server.dropped = True
                self.close_connection = True
                self.connection.shutdown(socket.SHUT_RDWR)
                return
            self.send_response(response.status_code)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(response.content)))
            self.end_headers()
            self.wfile.write(response.content)

        do_POST = forward
        do_GET = forward

        def log_message(self, *args):
            pass

    gateway = ThreadingHTTPServer(("127.0.0.1", 0), Gateway)
    gateway.dropped = False
    thread = threading.Thread(target=gateway.serve_forever)
    thread.start()
    try:
        yield f"http://127.0.0.1:{gateway.server_port}", gateway
    finally:
        gateway.shutdown()
        gateway.server_close()
        thread.join(timeout=5)
        assert not thread.is_alive()


